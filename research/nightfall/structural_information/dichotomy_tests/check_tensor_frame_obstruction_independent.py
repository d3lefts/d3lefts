#!/usr/bin/env python3
"""Independent exact tensor-simplex frame-obstruction audit.

Reconstructs Kronecker row matrices, triple-relation ranks and dual code
minimum distances without using parallel instances' checker implementations.
Finite tests do NOT prove all q,L nor imply a quantum speedup.
"""
from itertools import product, combinations
from fractions import Fraction
from math import ceil

checks=0
def ck(cond,reason):
    global checks
    if not cond:raise AssertionError(reason)
    checks+=1

def rank(xs):
    piv={}
    for x in xs:
        while x:
            i=x.bit_length()-1
            if i in piv:x^=piv[i]
            else:piv[i]=x;break
    return len(piv)

def tensor_row(vs,q):
    w=0
    for j,indices in enumerate(product(range(q),repeat=len(vs))):
        if all((v>>a)&1 for v,a in zip(vs,indices)):
            w|=1<<j
    return w

def run_case(q,L,check_distance=True):
    D=tuple(range(1,1<<q))
    tuples=list(product(D,repeat=L))
    n=len(tuples);m=q**L
    rows=[tensor_row(vs,q) for vs in tuples]
    ck(n==(2**q-1)**L and len(set(rows))==n,("all distinct rows",q,L))
    ck(rank(rows)==m,("full row rank",q,L))
    index={word:i for i,word in enumerate(tuples)}
    relations=[]
    for axis in range(L):
        for other in product(D,repeat=L-1):
            for u,v in combinations(D,2):
                w=u^v
                assert w in D
                def key(z):
                    it=iter(other)
                    return tuple(z if j==axis else next(it) for j in range(L))
                a=index[key(u)];b=index[key(v)];c=index[key(w)]
                rel=(1<<a)^(1<<b)^(1<<c)
                ck(rows[a]^rows[b]^rows[c]==0,
                   ("tensor local triangle",q,L,axis,other,u,v))
                relations.append(rel)
    ck(rank(relations)==n-m,("all relations generated by triangles",q,L,n,m))
    if check_distance:
        ck(m<=16, "only finite exhaustible m")
        best=n+1
        witness=0
        for linear in range(1,1<<m):
            weight=sum(((linear&r).bit_count()&1) for r in rows)
            if weight<best:
                best=weight;witness=linear
        delta=2**((q-1)*L)
        ck(best==delta,("exact dual distance",q,L,best,delta,witness))
        cmin=ceil(Fraction(m*delta,n))
        ck(cmin>=1 and cmin*n>=m*delta and (cmin-1)*n<m*delta,
           ("exact frame-width rounding",q,L,cmin))
        print(f'q={q} L={L}: n={n}, m={m}, triangle kernel rank={n-m}, dual distance={delta}, c_min≥{cmin}')
    else:
        print(f'q={q} L={L}: n={n}, m={m}, triangle kernel rank={n-m}; dual distance is symbolic only')

for q,L in [(2,1),(2,2),(2,3),(2,4),(3,1),(3,2),(4,1),(4,2),(2,5)]:
    run_case(q,L,check_distance=(q,L)!=(2,5))
# Correct sumset counting: even r=1 contains 0 plus all n distinct rows.
for q,L in [(2,2),(2,3),(3,2),(4,2)]:
    n=(2**q-1)**L
    ck(n+1>n and n+1<=(n+1)**1,("at most one row includes zero",q,L))
    for r in range(1,5):
        ck((n+1)**r>n**r,("naive n^r bound invalid",q,L,r))
# Exact near-linear exponent without floating-point comparisons:
# q=2^s gives mΔ/n=(q/(2*(1-2^-q)))^L > (q/2)^L = m^(1-1/s).
for s in range(2,10):
    q=1<<s
    ck(Fraction(q*(1<<(q-1)),(1<<q)-1)>Fraction(q,2),
       ("near-linear exponent strict gap",s))
print(f'PASS independent tensor-simplex audit: {checks} exact assertions, 9 relation-kernel cases, 8 dual-distance enumerations.')
print('LIMIT: universal relation-distance theorem and quantum gap require independent proof review; frame converse only is disproved.')
