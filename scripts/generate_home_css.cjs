"use strict";
// Preserve the original stylesheet cascade, including the local theme import.
// Run from repository root: node scripts/generate_home_css.cjs [--check]
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..","docs");
const sources=["site.css","home-rhythm.css","ethereal-theme.css","home-dual-experience.css","two-skies.css","mobile-scroll-cinema.css","home-opening-cinema.css","experience-pages.css","publications.css"];
function build(read){
  return "/* Generated by scripts/generate_home_css.cjs; do not edit directly. */\n"+sources.map(name=>{
    let css=read(name);
    if(name==="ethereal-theme.css"){
      const marker='@import url("golden-hour-light.css");';
      if(!css.startsWith(marker))throw Error("Theme import moved: audit the cascade before rebuilding");
      const local=read("golden-hour-light.css");
      if(/@(?:import|charset|namespace)\b/i.test(local))throw Error("Unexpected directive in local theme");
      css=css.replace(marker,"/* golden-hour-light.css */\n"+local);
    }
    if(name!=="site.css"&&/@(?:import|charset|namespace)\b/i.test(css))throw Error("Unexpected stylesheet directive: "+name);
    return "/* "+name+" */\n"+css+"\n";
  }).join("\n");
}
module.exports={build,sources};
if(require.main===module){
  const read=name=>fs.readFileSync(path.join(root,name),"utf8");
  const output=build(read);
  if(process.argv.includes("--check")){
    if(read("home-bundle.css")!==output)throw Error("Stale homepage CSS bundle");
  }else fs.writeFileSync(path.join(root,"home-bundle.css"),output);
}
