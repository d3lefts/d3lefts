#!/usr/bin/env python3
"""Generate an exact flat-module Lake manifest from committed Lean imports.

This is a source dependency enumerator, NOT a theorem checker. It scans only
original source files and does not synthesize lemmas or silently omit imports.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "research/nightfall/formalization"
OUTPUT = ROOT / "lakefile.toml"
SEEDS = (
    "ActualSourceQ2107Terminal",
    "CubicTopCover105416",
    "CubicTopCoverEnergy",
    "CubicTopCoverProjection",
    "InfinitePiQ2Limit",
    "InfinitePiQ2SourceHilbertTensor",
    "Q2ShiftedConditionalTargets",
)
EXTERNAL_PREFIXES = (
    "Mathlib", "Lean", "Std", "Batteries", "Qq", "Aesop",
    "Cli", "ProofWidgets", "Plausible", "LeanSearchClient",
    "ImportGraph", "Lake",
)
# The active Mathlib revision comes from the same lock as the shared Lean CI action.
# Historical source receipts are intentionally not migrated by this generator.
def locked_mathlib_commit() -> str:
    lock = json.loads((ROOT / "docs/lean-compiler-lock.json").read_text(encoding="utf-8"))
    if lock.get("schema") != "nightfall-lean-compiler-lock/v1":
        raise RuntimeError("Unknown Lean compiler lock schema")
    commit = lock.get("mathlib_commit")
    if not isinstance(commit, str) or not re.fullmatch(r"[a-f0-9]{40}", commit):
        raise RuntimeError("Mathlib Git commit absent from compiler lock")
    return commit


def discover() -> tuple[dict[str, Path], dict[str, set[str]]]:
    by_name: dict[str, Path] = {}
    for file in SOURCE.rglob("*.lean"):
        name = file.stem
        if name in by_name:
            raise RuntimeError(
                f"Ambiguous flat module {name}: {by_name[name]} and {file}"
            )
        by_name[name] = file
    if not by_name:
        raise RuntimeError("No Lean sources found")

    imports: dict[str, set[str]] = {}
    for module, path in by_name.items():
        deps = set()
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            # Strip the common single-line comment form; don't mistake prose
            # in docstrings for imports, since sources import at top level.
            if line.lstrip().startswith(("--", "/-", "*", "#")):
                continue
            match = re.match(r"^(?:(?:public|private|protected)\s+)?import\s+(.+)$", line)
            if not match:
                continue
            for token in match.group(1).split("--", 1)[0].split():
                if re.fullmatch(r"[A-Za-z0-9_.]+", token):
                    deps.add(token)
                else:
                    raise RuntimeError(f"{path}:{lineno}: malformed import {token!r}")
        imports[module] = deps
    return by_name, imports


def closure(by_name: dict[str, Path], imports: dict[str, set[str]]) -> list[str]:
    missing = set(SEEDS) - by_name.keys()
    if missing:
        raise RuntimeError(f"Missing terminal source modules: {sorted(missing)}")
    visited = set()
    stack = list(SEEDS)
    while stack:
        module = stack.pop()
        if module in visited:
            continue
        visited.add(module)
        for dep in imports[module]:
            if dep in by_name:
                stack.append(dep)
            elif dep == "Mathlib" or any(
                dep.startswith(prefix + ".") for prefix in EXTERNAL_PREFIXES
            ):
                continue
            else:
                raise RuntimeError(
                    f"{module}: unknown imported module {dep}; "
                    "add its original source or an explicitly pinned dependency"
                )
    return sorted(visited)


def render(by_name: dict[str, Path], modules: list[str]) -> str:
    grouped: dict[str, list[str]] = defaultdict(list)
    for name in modules:
        grouped[by_name[name].parent.name].append(name)
    header = '''# GENERATED by scripts/generate_nightfall_lake.py.
# Do not edit roots/globs manually. Exact original-source import closure;
# its existence is not evidence of unconditional problem resolution.
name = "nightfall"
version = "0.1.0"
defaultTargets = ["Nightfall"]

[[require]]
name = "mathlib"
scope = "leanprover-community"
rev = "'''+locked_mathlib_commit()+'''"

[[lean_lib]]
name = "Nightfall"
'''
    blocks = []
    for directory in sorted(grouped):
        mods = sorted(grouped[directory])
        lib_name = "".join(part.capitalize() for part in directory.split("_"))
        # All selected flat modules are explicitly buildable, not just
        # terminal roots. Lake therefore discovers their imports across
        # source directories and can fail closed on missing source objects.
        names = ",\n".join(f'  "{m}"' for m in mods)
        blocks.append(
            '\n[[lean_lib]]\n'
            f'name = "Legacy{lib_name}"\n'
            f'srcDir = "research/nightfall/formalization/{directory}"\n'
            f'roots = [\n{names}\n]\n'
            f'globs = [\n{names}\n]\n'
        )
    return header + "".join(blocks)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true",
                        help="write the deterministic Lake TOML manifest")
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in Lake manifest is stale")
    args = parser.parse_args()
    if args.write and args.check:
        parser.error("choose --write or --check")
    files, imports = discover()
    modules = closure(files, imports)
    toml = render(files, modules)
    print(f"Source closure: {len(modules)} of {len(files)} Lean modules")
    print("Closure module paths:")
    for name in modules:
        print(" ", files[name].relative_to(ROOT))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != toml:
            raise SystemExit("FAIL: lakefile.toml differs from exact source closure")
        print("PASS: checked-in Lake manifest matches exact source closure")
    elif args.write:
        OUTPUT.write_text(toml, encoding="utf-8")
        print("WROTE:", OUTPUT.relative_to(ROOT))
    else:
        print(toml)


if __name__ == "__main__":
    main()
